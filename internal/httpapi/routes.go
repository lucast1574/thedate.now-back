package httpapi

import "net/http"

func (s *server) routes() http.Handler {
	mux := http.NewServeMux()
	handle := func(pattern string, handler http.HandlerFunc) { mux.HandleFunc(pattern, s.eventWriteGuard(handler)) }
	handle("GET /health", func(w http.ResponseWriter, r *http.Request) { reply(w, 200, map[string]string{"status": "ok"}) })
	handle("POST /auth/register", s.register)
	handle("POST /auth/login", s.login)
	handle("POST /auth/google", s.googleLogin)
	handle("GET /auth/me", s.me)
	handle("POST /devices", s.registerMobileDevice)
	handle("DELETE /devices/{installation}", s.removeMobileDevice)
	handle("GET /support/tickets", s.listSupportTickets)
	handle("POST /support/tickets", s.createSupportTicket)
	handle("GET /support/tickets/{id}/images/{index}", s.supportImage)
	handle("GET /admin/support/tickets", s.adminSupportTickets)
	handle("PATCH /admin/support/tickets/{id}", s.updateSupportTicket)
	handle("PATCH /profile", s.updateProfile)
	handle("DELETE /profile", s.deleteAccount)
	handle("POST /profile/professional", s.becomeProfessional)
	handle("POST /events/{id}/activate", s.activateDemo)
	handle("POST /profile/avatar", s.uploadAvatar)
	handle("GET /profile/avatar", s.profileAvatar)
	handle("GET /admin/overview", s.adminOverview)
	handle("GET /admin/users", s.adminUsers)
	handle("GET /admin/users/{user}/events", s.adminUserEvents)
	handle("PATCH /admin/users/{user}/role", s.adminRole)
	handle("POST /admin/events/{id}/courtesy", s.adminCourtesy)
	handle("GET /admin/withdrawals", s.adminWithdrawals)
	handle("PATCH /admin/users/{user}/withdrawals/{withdrawal}", s.adminWithdrawal)
	handle("GET /affiliates", s.affiliateOverview)
	handle("POST /affiliates/join", s.affiliateJoin)
	handle("POST /affiliates/withdrawals", s.affiliateWithdraw)
	handle("GET /events/{id}/collaborators", s.listCollaborators)
	handle("POST /events/{id}/collaborators", s.inviteCouple)
	handle("DELETE /events/{id}/collaborators/{member}", s.revokeCollaborator)
	handle("GET /access-invites/{token}", s.coupleInviteDetails)
	handle("POST /access-invites/{token}/accept", s.acceptCouple)
	handle("GET /events", s.listEvents)
	handle("GET /templates", s.listTemplates)
	handle("POST /events", s.createEvent)
	handle("PATCH /events/{id}", s.updateEvent)
	handle("PATCH /events/{id}/design", s.updateDesign)
	handle("POST /events/{id}/design/publish", s.publishDesign)
	handle("POST /maps/resolve", s.resolveMapsURL)
	handle("GET /events/{id}/wishlist", s.getWishlist)
	handle("PATCH /events/{id}/wishlist", s.saveWishlist)
	handle("POST /events/{id}/wishlist/metadata", s.giftMetadata)
	handle("PATCH /events/{id}/wishlist/reservations/{gift}", s.updateGiftReservation)
	handle("GET /events/{id}/wishlist/images/{gift}", s.wishlistImage)
	handle("GET /public/wishlist/{token}", s.publicWishlist)
	handle("POST /public/wishlist/{token}", s.chooseGift)
	handle("GET /public/wishlist/{token}/images/{gift}", s.wishlistImage)
	handle("GET /events/{id}/guests", s.listGuests)
	handle("GET /events/{id}/seating", s.getSeating)
	handle("PATCH /events/{id}/seating", s.saveSeating)
	handle("POST /events/{id}/guests", s.addGuest)
	handle("PATCH /events/{id}/guests/{guestId}", s.manageGuest)
	handle("DELETE /events/{id}/guests/{guestId}", s.manageGuest)
	handle("POST /events/{id}/guests/import", s.importGuests)
	handle("POST /events/{id}/audio", s.uploadAudio)
	handle("GET /events/{id}/audio/{key}", s.ownerAudio)
	handle("GET /public/events/{kind}/{slug}/audio/{key}", s.publicAudio)
	handle("POST /events/{id}/photos", s.uploadPhoto)
	handle("GET /events/{id}/photos/{key}", s.ownerPhoto)
	handle("POST /events/{id}/send-invitations", s.sendInvitations)
	handle("POST /events/{id}/delivery", s.startDelivery)
	handle("POST /events/{id}/delivery/retry", s.retryDelivery)
	handle("GET /events/{id}/delivery", s.deliveryStatus)
	handle("POST /events/{id}/couple-invitations", s.inviteCouple)
	handle("POST /events/{id}/couple-accounts", s.createCoupleAccount)
	handle("GET /couple-invites/{token}", s.coupleInviteDetails)
	handle("POST /couple-invites/{token}/accept", s.acceptCouple)
	handle("GET /public/events/{kind}/{slug}", s.publicEvent)
	handle("GET /public/events/{kind}/{slug}/wishlist", s.wishlistCatalog)
	handle("GET /public/events/{kind}/{slug}/wishlist/images/{gift}", s.wishlistCatalogImage)
	handle("POST /public/events/{kind}/{slug}/wishlist/access", s.wishlistAccess)
	handle("GET /public/events/{kind}/{slug}/photos/{key}", s.publicPhoto)
	handle("POST /public/rsvp/{token}", s.rsvp)
	handle("GET /public/rsvp/{token}", s.rsvpDetails)
	handle("POST /events/{id}/checkout", s.checkout)
	handle("POST /events/{id}/publish", s.publish)
	handle("GET /events/{id}/deployment", s.deploymentStatus)
	handle("POST /webhooks/stripe", s.stripeWebhook)
	handle("POST /webhooks/wazend", s.wazendWebhook)
	return cors(s.rateLimit(mux))
}
